def S(id, title, desc, code, ins, outs, partner=None, event=None):
    """One sub-step: `code` is "path/in/package.py::Symbol"."""
    return {"id": id, "title": title, "desc": desc, "code": code, "inputs": ins,
            "outputs": outs, "partner": partner, "event": event}


def N(id, title, partners, desc, code, col, row, subs, ins, outs, used_for, status="code",
      kind="step", lane=""):
    return {"id": id, "title": title, "partners": partners, "desc": desc, "code": code,
            "col": col, "row": row, "subs": subs, "inputs": ins, "outputs": outs,
            "used_for": used_for, "status": status, "kind": kind, "lane": lane}


